std::string_view patternName(Pattern pattern) {
    return pattern == Pattern::ZigZag ? "ZIG_ZAG_MOVEMENT" : "SPIRAL_MOVEMENT";
}

std::optional<Pattern> patternFromName(std::string_view name) {
    for (const Pattern pattern : {Pattern::Spiral, Pattern::ZigZag}) {
        if (patternName(pattern) == name) {
            return pattern;
        }
    }
    return std::nullopt;
}

std::string_view startPositionName(StartPosition position) {
    switch (position) {
        case StartPosition::BackLeft: return "START_POSITION_BACK_LEFT";
        case StartPosition::BackRight: return "START_POSITION_BACK_RIGHT";
        case StartPosition::FrontLeft: return "START_POSITION_FRONT_LEFT";
        case StartPosition::FrontRight: return "START_POSITION_FRONT_RIGHT";
        case StartPosition::Center: return "START_POSITION_CENTER";
    }
    return "START_POSITION_BACK_LEFT";
}

std::optional<StartPosition> startPositionFromName(std::string_view name) {
    for (const StartPosition position : {StartPosition::BackLeft, StartPosition::BackRight, StartPosition::FrontLeft,
                                         StartPosition::FrontRight, StartPosition::Center}) {
        if (startPositionName(position) == name) {
            return position;
        }
    }
    return std::nullopt;
}

std::vector<std::string> generateLines(const Options& options, bool metric) {
    return Generator(options, metric).generate();
}

std::string generate(const Options& options, bool metric) {
    const std::vector<std::string> lines = generateLines(options, metric);
    std::string text;
    for (std::size_t i = 0; i < lines.size(); ++i) {
        if (i != 0) {
            text += '\n';
        }
        text += lines[i];
    }
    return text;
}

Options toImperial(Options mm) {
    mm.bitDiameter = convertToImperial(mm.bitDiameter);
    mm.feedrate = convertToImperial(mm.feedrate);
    mm.length = convertToImperial(mm.length);
    mm.width = convertToImperial(mm.width);
    mm.skimDepth = convertToImperial(mm.skimDepth);
    mm.maxDepth = convertToImperial(mm.maxDepth);
    return mm;
}

Options toMetric(Options inches) {
    inches.bitDiameter = convertToMetric(inches.bitDiameter);
    inches.feedrate = convertToMetric(inches.feedrate);
    inches.length = convertToMetric(inches.length);
    inches.width = convertToMetric(inches.width);
    inches.skimDepth = convertToMetric(inches.skimDepth);
    inches.maxDepth = convertToMetric(inches.maxDepth);
    return inches;
}

