FirmwareValues currentFirmwareValues(const protocol::OrderedMap& settings) {
    FirmwareValues values;
    for (const char* key : {"$101", "$111", "$20", "$21"}) {
        values.emplace_back(key, settings.get(key));
    }
    return values;
}

std::vector<std::string> modeSwitchCommands(const ModeSwitch& change, const protocol::OrderedMap& settings) {
    std::vector<std::string> commands;
    if (!change.grblHal) {
        if (change.enable) {
            commands.emplace_back("G10 L20 P1 Y0");  // zero Y where it is
        }
        for (const auto& [key, value] : change.grblSettings) {
            commands.push_back(key + "=" + value);
        }
    } else {
        commands.emplace_back("G10 L20 P1 Y0");
        // A takes Y's settings and Y takes A's (both ways, the same swap).
        static constexpr std::pair<const char*, const char*> kPairs[] = {
            {"$103", "$101"}, {"$113", "$111"}, {"$123", "$121"}, {"$133", "$131"}};
        for (const auto& [a, y] : kPairs) {
            if (settings.has(y) && settings.has(a)) {
                commands.push_back(std::string(a) + "=" + settings.get(y));
            }
        }
        for (const auto& [a, y] : kPairs) {
            if (settings.has(y) && settings.has(a)) {
                commands.push_back(std::string(y) + "=" + settings.get(a));
            }
        }
    }
    commands.emplace_back("$$");
    for (const std::string& line : toggleMacro()) {
        commands.push_back(line);
    }
    return commands;
}

std::string mountingProgramName(const MountingSetup& setup) {
    const bool quarter = setup.quarterInchBit;
    if (!setup.linesUp) {
        return quarter ? "DOESNT_LINE_UP_QUARTER" : "DOESNT_LINE_UP_EIGHTH";  // a custom mounting: 2 holes
    }
    if (setup.holes != 10) {
        return quarter ? "QUARTER_INCH_SIX_HOLES" : "EIGHTH_INCH_SIX_HOLES";  // the standard 30" track
    }
    if (setup.longExtension) {
        return quarter ? "QUARTER_INCH_TEN_HOLES" : "EIGHTH_INCH_TEN_HOLES";  // with the 460 mm extension
    }
    return quarter ? "QUARTER_INCH_TEN_HOLES_SHORT" : "EIGHTH_INCH_TEN_HOLES_SHORT";
}

std::optional<std::string> mountingProgram(const MountingSetup& setup) {
    const std::optional<std::string_view> data = resources::find("data/rotary_mounting.json");
    if (!data) {
        return std::nullopt;
    }
    boost::system::error_code error;
    const json::value root = json::parse(*data, error);
    if (error || !root.is_object()) {
        return std::nullopt;
    }
    const json::value* holeTypes = root.as_object().if_contains("holeTypes");
    const json::value* program =
        holeTypes && holeTypes->is_object() ? holeTypes->as_object().if_contains(mountingProgramName(setup)) : nullptr;
    if (!program || !program->is_string()) {
        return std::nullopt;
    }
    return std::string(program->as_string());
}

